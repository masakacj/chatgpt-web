import Foundation

var assertions = 0
func expect(_ condition: @autoclosure () -> Bool, _ name: String) {
    assertions += 1
    guard condition() else { fatalError("FAILED: \(name)") }
}
var store = STDraftLedger()
store.edit("server1|A", text: "draft A")
store.edit("server1|B", text: "draft B")
expect(store.draft("server1|A").text == "draft A", "A is independent")
expect(store.draft("server1|B").text == "draft B", "B is independent")
expect(store.draft("server2|A").text.isEmpty, "server identity isolates drafts")
let before = store.draft("server1|A").revision
store.edit("server1|A", text: "draft A")
expect(store.draft("server1|A").revision == before, "unchanged text does not bump revision")
let first = try store.reserve("server1|A", server: "server1", temporary: false, id: "one-send")
expect(first.text == "draft A", "submission freezes text")
expect(store.pendingFor("server1|A")?.id == first.id, "reservation precedes submission")
do { _ = try store.reserve("server1|A", server: "server1", temporary: false); fatalError("duplicate reservation accepted") } catch STLedgerError.pendingSend { assertions += 1 }
let other = try store.reserve("server1|B", server: "server1", temporary: false, id: "other-send")
expect(other.owner == "server1|B", "A pending does not globally lock B")
store.edit("server1|A", text: "next draft A")
store.confirmed(first.id)
expect(store.draft("server1|A").text == "next draft A", "late receipt preserves newer text")
expect(store.pendingFor("server1|A") == nil, "confirmed reservation clears")
store.definitelyNotSent(other.id)
expect(store.draft("server1|B").text == "draft B", "definite failure preserves text")
expect(store.pendingFor("server1|B") == nil, "definite failure unblocks owner")
let b = try store.reserve("server1|B", server: "server1", temporary: false, id: "confirmed-B")
store.confirmed(b.id)
expect(store.draft("server1|B").text.isEmpty, "confirmed exact submitted revision clears")
expect(store.draft("server1|A").text == "next draft A", "other owner's confirmation does not alter A")
store.edit("server1|new:project", text: "first project message")
let new = try store.reserve("server1|new:project", server: "server1", temporary: true, id: "first-new")
store.edit("server1|new:project", text: "second project message")
store.confirmed(new.id, actualOwner: "server1|real-project-chat")
expect(store.draft("server1|real-project-chat").text == "second project message", "next draft follows verified newly created ID")
expect(store.draft("server1|new:project").text.isEmpty, "temporary slot clears after moving next draft")
store.edit("server1|new:", text: "ordinary first")
let new2 = try store.reserve("server1|new:", server: "server1", temporary: true, id: "new-exact")
store.confirmed(new2.id, actualOwner: "server1|real-ordinary")
expect(store.draft("server1|new:").text.isEmpty, "new chat exact sent text clears")
expect(store.draft("server1|real-ordinary").text.isEmpty, "sent text is not copied into real-chat composer")
store.edit("server1|unknown", text: "do not replay")
let unknown = try store.reserve("server1|unknown", server: "server1", temporary: false, id: "unknown-id")
let bytes = try JSONEncoder().encode(store)
let restored = try JSONDecoder().decode(STDraftLedger.self, from: bytes)
expect(restored.pending[unknown.id] == unknown, "unknown reservation survives process restart")
expect(restored.draft("server1|unknown").text == "do not replay", "unknown draft survives process restart")
expect(restored.draft("server1|A").text == "next draft A", "all drafts survive persistence")
var conflicting = STDraftLedger()
conflicting.edit("new", text: "first")
let p = try conflicting.reserve("new", server: "s", temporary: true)
conflicting.edit("new", text: "next")
conflicting.edit("real", text: "already typed in real chat")
conflicting.confirmed(p.id, actualOwner: "real")
expect(conflicting.draft("real").text == "already typed in real chat", "migration never overwrites destination draft")
expect(conflicting.draft("new").text == "next", "conflicting source draft remains recoverable")
do { _ = try STDraftLedger().draft("none"); var empty = STDraftLedger(); _ = try empty.reserve("none", server: "s", temporary: false); fatalError("empty send accepted") } catch STLedgerError.emptyDraft { assertions += 1 }
print("Shared-tab draft policy: \(assertions) assertions PASS")
